/**
 * Token generator core: pure (no fs), shared by `scripts/gen-tokens.ts` and the drift test.
 *
 * Source of truth: `packages/ui/tokens/<group>.json`, one file per group, each shaped
 * `{ "<group>": { ...nested tree... } }`. Leaves are CSS value strings or references to another
 * token written as `{dot.path}` (e.g. `"{color.text.muted}"`), resolved to the literal value in
 * both outputs. A group that is also a token itself keeps its own value under `$value`
 * (`bg: { "$value": "…", "day": "…" }` → `--…-bg` and `--…-bg-day`; in TS `bg.$value`, `bg.day`).
 *
 * Naming (spec §0): token = dot path (`color.moodle.neg.3.bg`), CSS var = same path with dots
 * replaced by `-` and a `--` prefix (`--color-moodle-neg-3-bg`), TS = `tokens.color.moodle.neg[3].bg`.
 */

export type TokenTree = { readonly [key: string]: string | TokenTree };

/** Output order of the groups (matches the spec's `:root` block). Every group file must be listed. */
export const TOKEN_GROUPS = [
  'color',
  'font',
  'space',
  'radius',
  'border',
  'shadow',
  'blur',
  'opacity',
  'motion',
  'z',
  'size',
] as const;

export type TokenGroup = (typeof TOKEN_GROUPS)[number];

export interface FlatToken {
  /** Dot path, e.g. `color.moodle.neg.3.bg`. */
  path: string;
  value: string;
}

const kebab = (s: string): string => s.replace(/([a-z])([A-Z])/g, '$1-$2').toLowerCase();

/** `color.moodle.neg.3.bg` → `--color-moodle-neg-3-bg` */
export const cssVarName = (path: string): string => `--${kebab(path).replace(/\./g, '-')}`;

/** Merges per-group files into one tree, validating shape and group names. */
export function mergeGroups(files: Readonly<Record<string, unknown>>): TokenTree {
  const tree: Record<string, TokenTree> = {};
  const known = new Set<string>(TOKEN_GROUPS);
  for (const [file, content] of Object.entries(files)) {
    if (!isRecord(content)) throw new Error(`${file}: expected a JSON object`);
    const keys = Object.keys(content);
    if (keys.length !== 1 || keys[0] !== file) {
      throw new Error(`${file}.json must contain exactly one top-level key "${file}"`);
    }
    if (!known.has(file))
      throw new Error(`${file}.json: unknown token group (add it to TOKEN_GROUPS)`);
    tree[file] = assertTree(content[file], file);
  }
  const ordered: Record<string, TokenTree> = {};
  for (const group of TOKEN_GROUPS) {
    const g = tree[group];
    if (!g) throw new Error(`missing token group file: tokens/${group}.json`);
    ordered[group] = g;
  }
  return resolveRefs(ordered);
}

const REF = /^\{([A-Za-z0-9.-]+)\}$/;
/** Own value of a node that also has children (see file header). */
export const SELF = '$value';
const leafPath = (prefix: readonly string[], key: string): string[] =>
  key === SELF ? [...prefix] : [...prefix, key];

/** Replaces `{dot.path}` leaves with the referenced value (chains allowed, cycles rejected). */
export function resolveRefs(tree: TokenTree): TokenTree {
  const values = new Map(flatten(tree).map((t) => [t.path, t.value]));
  const resolve = (path: string, seen: string[]): string => {
    const value = values.get(path);
    if (value === undefined)
      throw new Error(`${seen.at(-1) ?? path}: unknown token reference {${path}}`);
    const ref = REF.exec(value)?.[1];
    if (ref === undefined) return value;
    if (seen.includes(ref)) throw new Error(`token reference cycle: ${[...seen, ref].join(' → ')}`);
    return resolve(ref, [...seen, ref]);
  };
  const walk = (node: TokenTree, prefix: string[]): TokenTree =>
    Object.fromEntries(
      Object.entries(node).map(([k, v]): [string, TokenTree | string] => {
        if (typeof v !== 'string') return [k, walk(v, [...prefix, k])];
        const path = leafPath(prefix, k).join('.');
        return [k, resolve(path, [path])];
      }),
    );
  return walk(tree, []);
}

export function flatten(tree: TokenTree, prefix: readonly string[] = []): FlatToken[] {
  const out: FlatToken[] = [];
  for (const [key, value] of Object.entries(tree)) {
    if (typeof value === 'string') out.push({ path: leafPath(prefix, key).join('.'), value });
    else out.push(...flatten(value, [...prefix, key]));
  }
  return out;
}

const HEADER =
  'GENERATED by `pnpm --filter @deadzone/ui gen:tokens` from packages/ui/tokens/*.json. Do not edit.';

export function toCss(tree: TokenTree): string {
  const lines = flatten(tree).map((t) => `  ${cssVarName(t.path)}: ${t.value};`);
  // prettier-ignore keeps values byte-identical to the JSON (no 0.70 → 0.7, no hex lowercasing).
  return `/* ${HEADER} */\n/* prettier-ignore */\n:root {\n${lines.join('\n')}\n}\n`;
}

export function toTs(tree: TokenTree): string {
  const paths = flatten(tree).map((t) => JSON.stringify(t.path));
  return [
    `// ${HEADER}`,
    '',
    `export const tokens = ${JSON.stringify(tree, null, 2)} as const;`,
    '',
    'export type Tokens = typeof tokens;',
    '',
    '/** Every token as a dot path, e.g. `color.moodle.neg.3.bg`. */',
    `export const tokenPaths = [${paths.join(', ')}] as const;`,
    '',
    'export type TokenPath = (typeof tokenPaths)[number];',
    '',
  ].join('\n');
}

function isRecord(v: unknown): v is Record<string, unknown> {
  return typeof v === 'object' && v !== null && !Array.isArray(v);
}

function assertTree(v: unknown, path: string): TokenTree {
  if (!isRecord(v)) throw new Error(`${path}: expected an object`);
  const out: Record<string, string | TokenTree> = {};
  for (const [k, child] of Object.entries(v)) {
    if (k === SELF) {
      if (typeof child !== 'string') throw new Error(`${path}.${k}: must be a value`);
    } else if (!/^[A-Za-z0-9-]+$/.test(k)) throw new Error(`${path}.${k}: invalid key`);
    if (typeof child === 'string') out[k] = child;
    else out[k] = assertTree(child, `${path}.${k}`);
  }
  return out;
}
