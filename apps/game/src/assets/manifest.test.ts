import { describe, expect, it } from 'vitest';
import committed from '../../public/models/manifest.json' with { type: 'json' };
import { assetUrl, findAsset, parseManifest } from './manifest.js';

const valid = () =>
  structuredClone(committed) as unknown as Record<string, unknown> & {
    packs: Record<string, unknown>[];
    assets: { pack: string; lods: { distance: number }[] }[];
  };

describe('parseManifest', () => {
  it('accepts the manifest generated by tools/assets', () => {
    const m = parseManifest(committed);
    expect(m.packs[0]?.licence).toBe('CC0-1.0');
    expect(m.assets.length).toBeGreaterThan(0);
    expect(findAsset(m, 'kenney-survival/barrel').lods[0]?.distance).toBe(0);
  });

  it('refuses assets without a licensed pack', () => {
    const m = valid();
    m.assets[0]!.pack = 'unknown';
    expect(() => parseManifest(m)).toThrow(/brak packa z licencją/);
    const n = valid();
    delete n.packs[0]!.licence;
    expect(() => parseManifest(n)).toThrow(/licence/);
  });

  it('rejects bad versions, non-increasing LOD distances and wrong types', () => {
    expect(() => parseManifest({ ...valid(), version: 2 })).toThrow(/wersja/);
    const m = valid();
    const lods = m.assets.find((a) => a.lods.length > 1)!.lods;
    lods[1]!.distance = 0;
    expect(() => parseManifest(m)).toThrow(/rosnąć/);
    expect(() => parseManifest({ version: 1, packs: {}, assets: [] })).toThrow(/packs/);
  });

  it('resolves files against the base URL', () => {
    expect(assetUrl('/models/', 'p/a.glb')).toBe('/models/p/a.glb');
    expect(assetUrl('/models', 'p/a.glb')).toBe('/models/p/a.glb');
    expect(() => findAsset(parseManifest(committed), 'nope')).toThrow(/nieznany/);
  });
});
