// Bundles the Edge Function (src/edge.ts) into supabase/functions/api/server.js (gitignored):
// workspace packages, npm dependencies and the places JSON in one ESM file for Deno. Only `node:`
// built-ins the Supabase Edge Runtime provides (crypto, zlib) stay external.
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';

const out = fileURLToPath(new URL('../../../supabase/functions/api/server.js', import.meta.url));

const result = await build({
  entryPoints: [fileURLToPath(new URL('../src/edge.ts', import.meta.url))],
  outfile: out,
  bundle: true,
  format: 'esm',
  platform: 'browser',
  conditions: ['deno', 'worker', 'browser', 'import'],
  target: 'es2022',
  external: ['node:*'],
  minifySyntax: true,
  minifyWhitespace: true,
  legalComments: 'none',
  metafile: true,
  banner: { js: '// Generated by apps/server/scripts/build-edge.mjs — do not edit.' },
  logLevel: 'warning',
});
const bytes = Object.values(result.metafile.outputs).reduce((n, o) => n + o.bytes, 0);
console.log(`edge bundle: ${out} (${(bytes / 1024).toFixed(0)} KiB)`);
